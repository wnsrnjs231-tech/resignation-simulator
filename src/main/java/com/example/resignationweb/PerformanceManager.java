package com.example.resignationweb;

// ==================================================
// 인사평가 관리 클래스
// 플레이어의 능력 / 평판 / 스트레스를 바탕으로
// 인사평가 점수를 계산
// ==================================================
public class PerformanceManager {

    // ==================================================
// 인사평가 점수 계산
// 최종 점수는 0 ~ 100 범위로 제한
// ==================================================
    public int calculateScore(
            Player player) {

        // --------------------------------------------------
        // 평가용 평판 계산
        // --------------------------------------------------

        int evaluatedReputation =
                player.reputation;

        // 팀장 지원 효과가 있으면
        // 평가용 평판에만 +5 적용
        if (player.teamLeaderSupportUnlocked) {

            evaluatedReputation +=
                    5;
        }


        // --------------------------------------------------
        // 인사평가 점수 계산
        // --------------------------------------------------

        int score =
                player.ability
                        + evaluatedReputation
                        - player.stress / 2;


        // --------------------------------------------------
        // 점수 범위 제한
        // 최소 0점 / 최대 100점
        // --------------------------------------------------

        score =
                Math.max(
                        0,
                        Math.min(
                                100,
                                score
                        )
                );


        // 최종 점수 반환
        return score;
    }

    // ==================================================
    // 인사평가 결과 등급 반환
    // 점수에 따라 평가 결과를 문자열로 반환
    // ==================================================
    public String getPerformanceGrade(
            int score) {

        // 매우 좋은 평가
        if (score >= 100) {

            return "A";
        }

        // 좋은 평가
        if (score >= 70) {

            return "B";
        }

        // 보통 평가
        if (score >= 40) {

            return "C";
        }

        // 좋지 않은 평가
        if (score >= 20) {

            return "D";
        }

        // 매우 낮은 평가
        return "F";
    }


    // ==================================================
    // 오늘이 인사평가 날짜인지 확인
    // ==================================================
    public boolean isPerformanceDay(
            int day) {

        // 30일차
        if (day == 30) {
            return true;
        }

        // 90일차
        if (day == 90) {
            return true;
        }

        // 180일차
        if (day == 180) {
            return true;
        }

        // 270일차
        if (day == 270) {
            return true;
        }

        // 그 외 날짜는 인사평가 아님
        return false;
    }

    // ==================================================
    // 권고사직 여부 확인
    // 수습평가 점수가 30점 미만이면 권고사직
    // ==================================================
    public boolean isRecommendedResignation(
            int score) {

        // 30점 미만이면 권고사직
        return score < 30;
    }


    // ==================================================
    // 인사평가 급여 조정
    // 90 / 180 / 270일차 평가 등급에 따라 급여 변경
    // ==================================================
    public int applySalaryAdjustment(
            Player player,
            String grade) {

        // --------------------------------------------------
        // 기존 월급 저장
        // --------------------------------------------------

        int oldSalary =
                player.salary;


        // --------------------------------------------------
        // A 등급
        // 월급 10% 인상
        // --------------------------------------------------

        if (grade.equals("A")) {

            player.salary =
                    (int) (player.salary * 1.10);
        }


        // --------------------------------------------------
        // B 등급
        // 월급 5% 인상
        // --------------------------------------------------

        else if (grade.equals("B")) {

            player.salary =
                    (int) (player.salary * 1.05);
        }


        // --------------------------------------------------
        // C 등급
        // 변동 없음
        // --------------------------------------------------

        else if (grade.equals("C")) {

            // 월급 그대로 유지
        }


        // --------------------------------------------------
        // D 등급
        // 월급 5% 감봉
        // --------------------------------------------------

        else if (grade.equals("D")) {

            player.salary =
                    (int) (player.salary * 0.95);
        }


        // --------------------------------------------------
        // F 등급
        // 월급 10% 감봉
        // --------------------------------------------------

        else if (grade.equals("F")) {

            player.salary =
                    (int) (player.salary * 0.90);
        }


        // --------------------------------------------------
        // 월급 변화량 반환
        // --------------------------------------------------

        return player.salary - oldSalary;
    }
}