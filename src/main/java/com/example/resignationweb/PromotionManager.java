package com.example.resignationweb;

// ==================================================
// 승진 관리 클래스
// 날짜에 따라 플레이어 직급을 변경
// ==================================================
public class PromotionManager {

    // ==================================================
    // 승진 조건 확인
    // 현재 날짜에 맞는 직급으로 변경
    // ==================================================
    public void checkPromotion(
            Player player) {


        // ==================================================
        // Day 90
        // 사원 → 대리
        // 최근 인사평가가 A 또는 B일 때 승진
        // ==================================================
        if (player.day >= 90
                && player.position.equals("사원")
                && canPromote(player)) {

            // ==================================================
            // 사원 → 대리 자동 승진
            // ==================================================

            player.position =
                    "대리";

            player.salary =
                    (int) (player.salary * 1.10);

            player.promotionMessage =
                    "🎉 대리로 승진했습니다. "
                            + "월급이 10% 인상되었습니다.";


            // --------------------------------------------------
            // 승진 급여 인상
            // 기존 월급 기준 10% 인상
            // --------------------------------------------------

            player.salary =
                    (int) (player.salary * 1.10);


            // --------------------------------------------------
            // 승진 처리 종료
            // --------------------------------------------------

            return;
        }

        // ==================================================
        // 대리 → 과장
        // 승진 조건을 만족하면 바로 승진하지 않고
        // 플레이어의 선택을 기다림
        // ==================================================

        if (player.day >= 180
                && player.position.equals("대리")
                && canPromote(player)
                && !player.promotionAbandoned
                && !player.promotionChoicePending) {


            // --------------------------------------------------
            // 과장 승진 선택 대기 상태
            // 실제 승진 여부는 플레이어가 화면에서 결정
            // --------------------------------------------------

            player.promotionChoicePending =
                    true;

            return;
        }

        // ==================================================
        // Day 270
        // 과장 → 차장
        // 최근 인사평가가 A 또는 B일 때 승진
        // ==================================================
        if (player.day >= 270
                && player.position.equals("과장")
                && canPromote(player)) {

            // ==================================================
            // 과장 → 차장 자동 승진
            // ==================================================

            player.position =
                    "차장";

            player.salary =
                    (int) (player.salary * 1.15);

            player.promotionMessage =
                    "🎉 차장으로 승진했습니다. "
                            + "월급이 15% 인상되었습니다.";


            // --------------------------------------------------
            // 승진 급여 인상
            // 기존 월급 기준 15% 인상
            // --------------------------------------------------

            player.salary =
                    (int) (player.salary * 1.15);


            // --------------------------------------------------
            // 승진 처리 종료
            // --------------------------------------------------

            return;
        }

        // ==================================================
        // Day 330
        // 차장 → 부장
        // 최근 인사평가가 A 또는 B일 때 승진
        // ==================================================
        if (player.day >= 330
                && player.position.equals("차장")
                && canPromote(player)) {

            // ==================================================
            // 차장 → 부장 자동 승진
            // ==================================================

            player.position =
                    "부장";

            player.salary =
                    (int) (player.salary * 1.20);

            player.promotionMessage =
                    "🎉 부장으로 승진했습니다. "
                            + "월급이 20% 인상되었습니다.";


            // --------------------------------------------------
            // 승진 급여 인상
            // 기존 월급 기준 20% 인상
            // --------------------------------------------------

            player.salary =
                    (int) (player.salary * 1.20);


            // --------------------------------------------------
            // 승진 처리 종료
            // --------------------------------------------------

            return;
        }
    }

    // ==================================================
    // 승진 가능 여부 확인
    // B 이상만 승진 가능
    // ==================================================
    private boolean canPromote(
            Player player) {

        // 최근 평가가 A 또는 B면 승진 가능
        return player.lastPerformanceGrade.equals("A")
                || player.lastPerformanceGrade.equals("B");
    }

    // ==================================================
    // 인사평가 급여 조정
    // 90 / 180 / 270일차 평가 등급에 따라 급여 변경
    // ==================================================
    public int applySalaryAdjustment(
            Player player,
            String grade) {

        // --------------------------------------------------
        // 기존 월급 저장
        // --------------------------------------------------

        int oldSalary =
                player.salary;


        // --------------------------------------------------
        // A 등급
        // 월급 10% 인상
        // --------------------------------------------------

        if (grade.equals("A")) {

            player.salary =
                    (int) (player.salary * 1.10);
        }


        // --------------------------------------------------
        // B 등급
        // 월급 5% 인상
        // --------------------------------------------------

        else if (grade.equals("B")) {

            player.salary =
                    (int) (player.salary * 1.05);
        }


        // --------------------------------------------------
        // C 등급
        // 변동 없음
        // --------------------------------------------------

        else if (grade.equals("C")) {

            // 월급 그대로 유지
        }


        // --------------------------------------------------
        // D 등급
        // 월급 5% 감봉
        // --------------------------------------------------

        else if (grade.equals("D")) {

            player.salary =
                    (int) (player.salary * 0.95);
        }


        // --------------------------------------------------
        // F 등급
        // 월급 10% 감봉
        // --------------------------------------------------

        else if (grade.equals("F")) {

            player.salary =
                    (int) (player.salary * 0.90);
        }


        // --------------------------------------------------
        // 월급 변화량 반환
        // --------------------------------------------------

        return player.salary - oldSalary;
    }
}