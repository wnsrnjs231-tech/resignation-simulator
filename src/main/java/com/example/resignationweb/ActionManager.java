package com.example.resignationweb;

// ==================================================
// 플레이어 행동 기록 관리자
// 이벤트 선택 결과에 따라 행동 횟수를 기록
// ==================================================
public class ActionManager {

    // ==================================================
    // 행동 기록
    // ==================================================
    public void recordAction(
            Player player,
            Event event,
            int choice) {

        // --------------------------------------------------
        // 야근
        // --------------------------------------------------

        if (event.type.equals("overtime")
                && choice == 1) {

            // 야근 횟수 증가
            player.overtimeCount++;

            return;
        }

        // --------------------------------------------------
        // 야근 택시 이용
        // --------------------------------------------------

        if (event.type.equals("taxi")
                && choice == 1) {

            // 택시 이용 횟수 증가
            player.taxiCount++;

            return;
        }


        // --------------------------------------------------
        // 커피
        // --------------------------------------------------

        if (event.type.equals("coffee")
                && choice == 1) {

            // 커피 구매 횟수 증가
            player.coffeeCount++;

            return;
        }


        // --------------------------------------------------
        // 회식
        // --------------------------------------------------

        if (event.type.equals("dinner")
                && choice == 1) {

            // 회식 참석 횟수 증가
            player.dinnerCount++;

            return;
        }


        // --------------------------------------------------
        // 주말 공부
        // --------------------------------------------------

        if (event.type.equals("weekend_study")
                && choice == 1) {

            // 공부 횟수 증가
            player.studyCount++;

            return;
        }


        // --------------------------------------------------
        // 업무 태만
        // --------------------------------------------------

        if (event.type.equals("workload")
                && choice == 2) {

            // 업무를 대충 한 횟수 증가
            player.neglectCount++;
        }
    }
}