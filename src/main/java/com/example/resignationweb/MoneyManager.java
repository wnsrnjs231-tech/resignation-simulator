package com.example.resignationweb;

// ==================================================
// 플레이어 돈 관리 클래스
// 이벤트 지출 / 생활비 / 마이너스 잔액 등을 처리
// ==================================================
public class MoneyManager {

    // ==================================================
    // 이벤트로 발생한 돈 변화 적용
    // ==================================================
    public void applyMoneyChange(
            Player player,
            int moneyChange) {

        // 현재 보유 금액에 변화량 적용
        player.money += moneyChange;
    }


    // ==================================================
    // 하루 생활비 처리
    // 매일 20,000원 지출
    // ==================================================
    public void payLivingCost(
            Player player) {

        // 하루 생활비 차감
        player.money -= 20_000;
    }

    // ==================================================
    // 마이너스 잔액 처리
    // 보유 금액이 0보다 작아지면 부족한 금액을 카드빚으로 전환
    // ==================================================
    public void handleNegativeBalance(
            Player player) {

        // 돈이 마이너스인 경우
        if (player.money < 0) {

            // 부족한 금액만큼 카드빚 증가
            player.cardDebt +=
                    Math.abs(
                            player.money
                    );

            // 현금 잔액은 0으로 복구
            player.money = 0;
        }
    }

    // ==================================================
    // 월급 지급
    // 30일마다 기본 월급을 지급하고
    // 카드빚이 있으면 월급에서 먼저 상환
    // ==================================================
    public void processSalary(
            Player player) {

        // ==================================================
        // 기본 월급 지급
        // ==================================================

        player.money +=
                player.salary;


        // ==================================================
        // 카드빚 상환
        // 카드빚이 있는 경우 현재 돈으로 먼저 갚음
        // ==================================================

        if (player.cardDebt > 0) {

            // 현재 돈으로 카드빚을 전부 갚을 수 있는 경우
            if (player.money >= player.cardDebt) {

                // 카드빚만큼 돈 차감
                player.money -=
                        player.cardDebt;

                // 카드빚 전액 상환
                player.cardDebt = 0;


                // 현재 돈으로 카드빚을 전부 갚을 수 없는 경우
            } else {

                // 현재 가지고 있는 돈만큼 카드빚 감소
                player.cardDebt -=
                        player.money;

                // 가지고 있던 돈은 모두 사용
                player.money = 0;
            }
        }
    }

    // ==================================================
    // 월세 납부
    // 돈이 부족하면 부족한 금액을 카드빚으로 전환
    // ==================================================
    public void payRent(
            Player player) {

        int rent =
                700_000;


        // --------------------------------------------------
        // 월세를 낼 돈이 충분한 경우
        // --------------------------------------------------

        if (player.money >= rent) {

            player.money -=
                    rent;

            return;
        }


        // --------------------------------------------------
        // 월세가 부족한 경우
        // 부족분을 카드빚으로 전환
        // --------------------------------------------------

        int shortage =
                rent - player.money;

        player.money =
                0;

        player.cardDebt +=
                shortage;
    }

    // ==================================================
    // 승진 관리자
    // 날짜에 따른 직급 변경 담당
    // ==================================================
    private final PromotionManager promotionManager =
            new PromotionManager();
}