package com.example.resignationweb;

// ==================================================
// 업무 태만 관리자
// 업무 태만 횟수에 따라 경고와 징계를 처리
// ==================================================
public class NeglectManager {

    // ==================================================
    // 업무 태만 상태 확인
    // ==================================================
    public String checkNeglect(
            Player player) {

        // --------------------------------------------------
        // 1차 경고
        // 업무 태만 5회
        // --------------------------------------------------

        if (player.neglectCount >= 5
                && !player.neglectWarning1) {

            // 1차 경고 처리
            player.neglectWarning1 =
                    true;

            // 경고 메시지 반환
            return "⚠️ 업무 태만이 반복되어 1차 경고를 받았습니다.";
        }


        // --------------------------------------------------
        // 2차 경고
        // 업무 태만 7회
        // --------------------------------------------------

        if (player.neglectCount >= 7
                && !player.neglectWarning2) {

            // 2차 경고 처리
            player.neglectWarning2 =
                    true;

            // 경고 메시지 반환
            return "🚨 업무 태만이 계속되어 최종 경고를 받았습니다.";
        }


        // --------------------------------------------------
        // 징계
        // 업무 태만 10회
        // --------------------------------------------------

        if (player.neglectCount >= 10) {

            // 징계 선택 화면 활성화
            player.neglectDisciplinePending =
                    true;

            // 징계 안내 메시지 반환
            return "🚨 업무 태만이 10회 누적되어 징계 대상이 되었습니다.";
        }


        // 새 경고 없음
        return null;
    }
}