package com.example.resignationweb;


// ==================================================
// 게임 엔딩 관리자
// 플레이 중 발생하는 엔딩을 관리
// ==================================================
public class EndingManager {


    // ==================================================
    // 강제 엔딩 확인
    // 번아웃 / 파산 조건을 확인
    // ==================================================
    public void checkEnding(
            Player player) {

        // 이미 게임이 종료된 상태라면
        // 다른 엔딩으로 덮어쓰지 않음
        if (player.gameOver) {

            return;
        }


        // --------------------------------------------------
        // 번아웃 엔딩
        // 나쁜 엔딩
        // --------------------------------------------------

        if (player.stress >= 100) {

            // 게임 종료
            player.gameOver =
                    true;

            // 나쁜 엔딩
            player.goodEnding =
                    false;

            // 엔딩 메시지
            player.endingMessage =
                    "💀 번아웃 엔딩\n"
                            + "끝없는 업무와 스트레스를 버티지 못하고 회사를 떠났습니다.";

            return;
        }


        // ==================================================
        // 빚쟁이 엔딩
        // 카드빚이 300만원 이상이면 게임 종료
        // ==================================================

        if (player.cardDebt >= 3_000_000) {

            player.gameOver =
                    true;

            player.endingMessage =
                    "💳 빚쟁이 엔딩\n"
                            + "불어난 카드빚을 감당하지 못하고 "
                            + "직장 생활을 이어갈 수 없게 되었습니다.";

            return;
        }
    }


    // ==================================================
    // 자발적 퇴사 엔딩
    // 각 엔딩 조건을 독립적으로 검사
    // 여러 조건을 만족하면 복합 엔딩 처리
    // ==================================================
    public void processVoluntaryResignation(
            Player player) {


        // ==================================================
        // 게임 종료
        // 자발적 퇴사를 선택했으므로 기본적으로 게임 종료
        // ==================================================

        player.gameOver =
                true;


        // ==================================================
        // 조기 퇴사
        // 30일 이전 퇴사는 다른 조건과 관계없이 조기 퇴사
        // ==================================================

        if (player.day < 30) {

            player.goodEnding =
                    false;

            player.endingMessage =
                    "🏃 조기 퇴사 엔딩\n"
                            + "회사 생활이 자신과 맞지 않다고 판단하고 "
                            + "빠르게 새로운 길을 선택했습니다.";

            return;
        }


        // ==================================================
        // 각 엔딩 조건 독립 판정
        // ==================================================

        boolean abilityEnding =
                player.day >= 90
                        && player.ability >= 80
                        && player.reputation >= 60;

        boolean moneyEnding =
                player.day >= 90
                        && player.money >= 10_000_000;

        boolean workLifeEnding =
                player.day >= 90
                        && player.stress <= 30
                        && player.stamina >= 60;


        // ==================================================
        // 3개 조건 모두 만족
        // ==================================================

        if (abilityEnding
                && moneyEnding
                && workLifeEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "👑 완벽한 퇴사 엔딩\n"
                            + "실력과 평판, 충분한 자산, 그리고 건강한 삶까지 "
                            + "모두 지켜낸 채 회사를 떠났습니다.";

            return;
        }


        // ==================================================
        // 능력 + 자산
        // ==================================================

        if (abilityEnding
                && moneyEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "🚀💰 성공한 능력자 퇴사 엔딩\n"
                            + "회사에서 충분한 실력과 경력을 쌓고 "
                            + "든든한 자산까지 마련한 뒤 새로운 기회를 찾아 떠났습니다.";

            return;
        }


        // ==================================================
        // 능력 + 워라밸
        // ==================================================

        if (abilityEnding
                && workLifeEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "🚀🌿 여유로운 능력자 퇴사 엔딩\n"
                            + "높은 실력을 갖추면서도 자신의 삶을 잃지 않고 "
                            + "새로운 도전을 위해 회사를 떠났습니다.";

            return;
        }


        // ==================================================
        // 자산 + 워라밸
        // ==================================================

        if (moneyEnding
                && workLifeEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "💰🌿 여유로운 퇴사 엔딩\n"
                            + "충분한 자산을 마련하고 건강한 삶까지 유지한 채 "
                            + "여유롭게 새로운 길을 선택했습니다.";

            return;
        }


        // ==================================================
        // 능력자 퇴사
        // ==================================================

        if (abilityEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "🚀 능력자 퇴사 엔딩\n"
                            + "충분한 실력과 경력을 쌓은 뒤 "
                            + "새로운 기회를 찾아 떠났습니다.";

            return;
        }


        // ==================================================
        // 성공적인 퇴사
        // ==================================================

        if (moneyEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "💰 성공적인 퇴사 엔딩\n"
                            + "충분한 자금을 마련한 뒤 "
                            + "여유 있게 회사를 떠났습니다.";

            return;
        }


        // ==================================================
        // 워라밸 퇴사
        // ==================================================

        if (workLifeEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "🌿 워라밸 퇴사 엔딩\n"
                            + "회사 생활에 휩쓸리지 않고 "
                            + "자신의 삶을 선택했습니다.";

            return;
        }


        // ==================================================
        // 평범한 퇴사
        // 어떤 특별 엔딩 조건도 만족하지 못한 경우
        // ==================================================

        player.goodEnding =
                false;

        player.endingMessage =
                "🚪 평범한 퇴사 엔딩\n"
                        + "여러 고민 끝에 회사를 떠나 "
                        + "새로운 길을 선택했습니다.";
    }


    // ==================================================
// 365일 완주 엔딩
// 각 완주 엔딩 조건을 독립적으로 검사
// 여러 조건을 만족하면 복합 엔딩 처리
// ==================================================
    public void processSurvivalEnding(
            Player player) {


        // ==================================================
        // 각 완주 엔딩 조건 독립 판정
        // ==================================================

        boolean workLifeEnding =
                player.promotionAbandoned
                        && player.position.equals("대리");

        boolean eliteEnding =
                player.position.equals("부장")
                        && player.ability >= 80
                        && player.reputation >= 70;

        boolean wealthyEnding =
                player.money >= 10_000_000;


        // ==================================================
        // 게임 종료
        // 365일 완주 시 반드시 엔딩 처리
        // ==================================================

        player.gameOver =
                true;


        // ==================================================
        // 엘리트 + 자산가
        // ==================================================

        if (eliteEnding
                && wealthyEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "👑 엘리트 자산가 직장인 엔딩\n"
                            + "부장까지 승진하며 회사의 핵심 인재가 되었고, "
                            + "1천만 원 이상의 자산까지 모으며 "
                            + "완벽에 가까운 직장 생활 1년을 완주했습니다.";

            return;
        }


        // ==================================================
        // 워라밸 + 자산가
        // ==================================================

        if (workLifeEnding
                && wealthyEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "🌿💰 여유로운 워라밸 직장인 엔딩\n"
                            + "승진 경쟁에서는 벗어났지만 자신의 삶을 지키면서 "
                            + "충분한 자산까지 마련해 안정적인 1년을 완주했습니다.";

            return;
        }


        // ==================================================
        // 엘리트 직장인
        // ==================================================

        if (eliteEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "🏆 엘리트 직장인 엔딩\n"
                            + "1년 동안 수많은 일을 이겨내고 "
                            + "부장까지 승진하며 회사의 핵심 인재가 되었습니다.";

            return;
        }


        // ==================================================
        // 자산가 직장인
        // ==================================================

        if (wealthyEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "💰 자산가 직장인 엔딩\n"
                            + "직장 생활을 이어가면서 "
                            + "1천만 원 이상의 자산을 모으는 데 성공했습니다.";

            return;
        }


        // ==================================================
        // 워라밸 직장인
        // ==================================================

        if (workLifeEnding) {

            player.goodEnding =
                    true;

            player.endingMessage =
                    "🌿 워라밸 직장인 엔딩\n"
                            + "승진 경쟁에서 벗어나 자신의 삶을 지키며 "
                            + "대리로 1년의 회사 생활을 완주했습니다.";

            return;
        }


        // ==================================================
        // 기본 완주 엔딩
        // 특별한 완주 조건을 만족하지 못한 경우
        // ==================================================

        player.goodEnding =
                true;

        player.endingMessage =
                "🏢 1년 생존 엔딩\n"
                        + "365일의 직장 생활을 무사히 버텨냈습니다.";
    }
}